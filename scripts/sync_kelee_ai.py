#!/usr/bin/env python3
"""Strict, dependency-free Loon AI.lsr -> native Mihomo classical provider."""
import argparse
import base64
from collections import Counter
import hashlib
import ipaddress
from pathlib import Path
import re
import tempfile
from urllib.request import Request, urlopen

SOURCE_URL = 'https://kelee.one/Tool/Loon/Lsr/AI.lsr'
USER_AGENT = 'Loon/879 CFNetwork/3826.500.111.2.2 Darwin/24.4.0'
DEFAULT_OUTPUT = Path(__file__).resolve().parents[1] / 'ruleset/kelee-ai.yaml'
DOMAIN = r'(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?'
AND = re.compile(r'AND,\(\(DOMAIN-KEYWORD,([a-z0-9.-]+)\),\(DOMAIN-SUFFIX,(' + DOMAIN + r')\)\)')
MAX_BYTES = 2_000_000


def convert(source):
    rules, seen, counts = [], set(), Counter()
    for number, raw in enumerate(source.splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith(('#', ';', '//')):
            continue
        # Loon's insignificant whitespace is removed only after checking tokens.
        line = re.sub(r'\s*,\s*', ',', line)
        line = re.sub(r'\(\s*', '(', line)
        line = re.sub(r'\s*\)', ')', line)
        kind = line.split(',', 1)[0]
        parts = line.split(',')
        valid = False
        if kind in ('DOMAIN', 'DOMAIN-SUFFIX'):
            valid = len(parts) == 2 and re.fullmatch(DOMAIN, parts[1]) is not None
        elif kind == 'AND':
            # Preserve the intersection verbatim; never flatten into two rules.
            valid = AND.fullmatch(line) is not None
        elif kind in ('IP-CIDR', 'IP-CIDR6'):
            if len(parts) in (2, 3) and (len(parts) == 2 or parts[2] == 'no-resolve'):
                try:
                    network = ipaddress.ip_network(parts[1], strict=True)
                    valid = network.version == (6 if kind == 'IP-CIDR6' else 4)
                except ValueError:
                    pass
        if not valid:
            raise ValueError(f'line {number}: unsupported or malformed rule: {raw!r}')
        counts[kind] += 1
        if line not in seen:
            seen.add(line)
            rules.append(line)
    if not rules:
        raise ValueError('source contains no rules')
    digest = hashlib.sha256(source.encode('utf-8')).hexdigest()
    # Validated grammar contains no quotes, so YAML single-quoted scalars are safe.
    output = (f'# Source: {SOURCE_URL}\n# Source SHA256 (UTF-8): {digest}\n'
              '# Generated by scripts/sync_kelee_ai.py; native Mihomo classical, not clash-domain.\n'
              '# Do not pass this payload through subconverter clash-classic (AND would be lost).\n'
              'payload:\n' + ''.join(f"  - '{rule}'\n" for rule in rules))
    return output, counts, len(rules)


BEGIN = '; BEGIN KELEE AI COMPATIBLE'
END = '; END KELEE AI COMPATIBLE'


def compatible_rules(output):
    return [line[5:-1] for line in output.splitlines()
            if line.startswith("  - '") and not line.startswith("  - 'AND,")]


def update_ini(ini, output):
    rules = compatible_rules(output)
    content = ('\n'.join(rules) + '\n').encode('utf-8')
    encoded = base64.urlsafe_b64encode(content).decode('ascii')
    # The explicit final interval keeps the comma within the data URI in Url.
    block = (BEGIN + f'\n; Generated snapshot: {len(rules)} compatible rules; AND excluded; see KELEE_AI.md\n'
             'ruleset=💬 人工智能,data:text/plain;base64,' + encoded + ',86400\n' + END + '\n')
    if BEGIN in ini or END in ini:
        if ini.count(BEGIN) != 1 or ini.count(END) != 1:
            raise ValueError('invalid Kelee INI block markers')
        start, end = ini.index(BEGIN), ini.index(END) + len(END)
        if end <= start:
            raise ValueError('invalid Kelee INI block order')
        if ini[end:end + 1] == '\n':
            end += 1
        return ini[:start] + block + ini[end:]
    needle = 'ruleset=💬 人工智能,clash-domain:'
    if needle not in ini:
        raise ValueError('cannot locate existing AI rules in INI')
    return ini.replace(needle, block + needle, 1)


def write_atomic(path, content):
    with tempfile.NamedTemporaryFile(mode='w', encoding='utf-8', dir=path.parent,
                                     prefix='.' + path.name, delete=False) as temporary:
        temp_path = Path(temporary.name)
        try:
            temporary.write(content)
            temporary.flush()
            temp_path.chmod(0o644)
        except BaseException:
            temp_path.unlink(missing_ok=True)
            raise
    try:
        temp_path.replace(path)
    finally:
        temp_path.unlink(missing_ok=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, help='read a local Loon source instead of downloading')
    parser.add_argument('--output', type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument('--check', action='store_true', help='compare without writing')
    parser.add_argument('--update-ini', action='store_true', help='also sync the compatible embedded snapshot in ACL_mini.ini')
    parser.add_argument('--ini', type=Path, default=DEFAULT_OUTPUT.parents[1] / 'ACL_mini.ini')
    args = parser.parse_args()
    try:
        if args.source:
            data = args.source.read_bytes()
        else:
            with urlopen(Request(SOURCE_URL, headers={'User-Agent': USER_AGENT}), timeout=30) as response:
                data = response.read(MAX_BYTES + 1)
        if len(data) > MAX_BYTES:
            raise ValueError('source exceeds 2 MB limit')
        output, counts, unique = convert(data.decode('utf-8'))
        pending = [(args.output, output)]
        if args.update_ini:
            pending.append((args.ini, update_ini(args.ini.read_text(encoding='utf-8'), output)))
        if args.check:
            for path, content in pending:
                if path.read_text(encoding='utf-8') != content:
                    parser.exit(1, f'{path}: needs regeneration\n')
        else:
            for path, content in pending:
                write_atomic(path, content)
        print(f'{dict(counts)}; {sum(counts.values())} input, {unique} unique; {args.output}')
    except (OSError, UnicodeError, ValueError) as error:
        parser.exit(1, f'error: {error}\n')


if __name__ == '__main__':
    main()
